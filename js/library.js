  function niceRound(x) {
    if (x < 10) return Math.max(1, Math.round(x));
    if (x < 200) return Math.round(x / 5) * 5;
    return Math.round(x / 10) * 10;
  }
  function parseStats(spec) {
    const w = { str: 0, vit: 0, int: 0, will: 0, cha: 0, fin: 0 };
    let sum = 0;
    String(spec).replace(/([a-z]+)(\d+(?:\.\d+)?)/g, (_, k, n) => { if (k in w) { w[k] += +n; sum += +n; } return ''; });
    if (!sum) { w.will = 0.5; w.int = 0.5; return w; }
    for (const k in w) w[k] = Math.round((w[k] / sum) * 1000) / 1000;
    return w;
  }
  function mk(row, prof) {
    const [id, name, unitSpec, dose, mpd, intensity, statSpec, maxDaily, kw] = row;
    const [unit, label] = unitSpec.split(':');
    return {
      id: prof === 'common' ? id : prof + '_' + id, name, unit, unitLabel: label || C.UNITS[unit].fa,
      dose, mpd, intensity, xp: niceRound(mpd * C.K * intensity), stats: parseStats(statSpec),
      maxDaily, kw: T.norm(kw || '').split(' ').filter(Boolean), prof, source: 'library',
    };
  }

